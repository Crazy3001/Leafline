#[cfg(test)]
mod tests {
    use super::super::gamefont::read_line;
    use super::*;

    /// `text` drawn from the table as the game spaces it: a blank column between glyphs, two more
    /// after a 1, four for a space, and three after the slash.
    fn drawn(text: &str) -> Vec<Vec<bool>> {
        let mut rows = vec![String::new(); OBJECTIVE.rows];
        let mut previous: Option<char> = None;
        let mut spaced = false;
        for c in text.chars() {
            if c == ' ' {
                spaced = true;
                continue;
            }
            let glyph = GLYPHS.iter().find(|(g, _)| *g == c).expect("a known glyph").1;
            let gap = match previous {
                None => 0,
                Some('/') => 3,
                Some(p) if spaced => 4 + if p == '1' { 2 } else { 0 },
                Some('1') => 3,
                Some(_) => 1,
            };
            for (y, row) in rows.iter_mut().enumerate() {
                row.push_str(&".".repeat(gap));
                row.push_str(glyph[y]);
            }
            previous = Some(c);
            spaced = false;
        }
        rows.iter().map(|r| r.chars().map(|c| c == '#').collect()).collect()
    }

    #[test]
    fn reads_an_objective_line() {
        assert_eq!(read_line(&OBJECTIVE, &drawn("23 / 20 Orange Mushroom Cap")), "23 /20 Orange Mushroom Cap");
        assert_eq!(read_line(&OBJECTIVE, &drawn("10 / 10 Slime")), "10 /10 Slime");
        assert_eq!(read_line(&OBJECTIVE, &drawn("0 / 1 Pig's Head")), "0 /1 Pig's Head");
    }

    #[test]
    fn every_glyph_reads_as_itself() {
        for (c, _) in GLYPHS {
            assert_eq!(read_line(&OBJECTIVE, &drawn(&c.to_string())), c.to_string());
        }
    }

    #[test]
    fn widths_and_shapes_never_tie() {
        for (i, (a, rows_a)) in GLYPHS.iter().enumerate() {
            assert_eq!(rows_a.len(), OBJECTIVE.rows, "{a}");
            for (b, rows_b) in &GLYPHS[i + 1..] {
                assert!(a != b, "{a} twice");
                assert!(rows_a != rows_b, "{a} and {b} are drawn alike");
            }
        }
    }
}
